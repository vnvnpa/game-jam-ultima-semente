# ---------------- acentos (2 linhas); posição relativa ao centro do glifo
ACC = {"acute": [(1, 0), (0, 1)], "grave": [(-1, 0), (0, 1)], "circ": [(0, 0), (-1, 1), (1, 0 + 1)],
       "tilde": [(-2, 1), (-1, 0), (0, 0), (1, 1)], "ced": "ced"}
COMP = {}
for base, accs in {"a": "áàâã", "e": "éèê", "i": "í", "o": "óòôõ", "u": "úù", "c": "ç",
                   "A": "ÁÀÂÃ", "E": "ÉÈÊ", "I": "Í", "O": "ÓÒÔÕ", "U": "ÚÙ", "C": "Ç"}.items():
    kinds = {"á": "acute", "à": "grave", "â": "circ", "ã": "tilde", "é": "acute", "è": "grave", "ê": "circ",
             "í": "acute", "ó": "acute", "ò": "grave", "ô": "circ", "õ": "tilde", "ú": "acute", "ù": "grave",
             "ç": "ced", "Á": "acute", "À": "grave", "Â": "circ", "Ã": "tilde", "É": "acute", "È": "grave",
             "Ê": "circ", "Í": "acute", "Ó": "acute", "Ò": "grave", "Ô": "circ", "Õ": "tilde", "Ú": "acute",
             "Ù": "grave", "Ç": "ced"}
    for a in accs:
        COMP[a] = (base, kinds[a])


def glyph_pixels(ch):
    """Retorna (conjunto de (x, y) com y=0 na linha do topo das maiúsculas, largura)."""
    if ch in G:
        rows = G[ch]
        w = max(len(r) for r in rows)
        return {(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "#"}, w
    base, kind = COMP[ch]
    pts, w = glyph_pixels(base)
    pts = set(pts)
    cx = w // 2
    upper = base.isupper()
    if kind == "ced":
        pts |= {(cx, 7), (max(cx - 1, 0), 8)}
        return pts, w
    if base == "i":
        pts = {p for p in pts if p[1] >= 2}
    dy = -2 if upper else 0
    if base in "aeou" and not upper:
        dy = 0
    for (ox, oy) in ACC[kind]:
        pts.add((cx + ox, dy + oy))
    return pts, w


def build():
    chars = list(G.keys()) + list(COMP.keys())
    asc_rows = 9   # linhas acima da linha-base (maiúscula com acento)
    base_row = 7   # a linha-base fica entre as linhas 6 e 7
    glyphs, metrics, cmap = {}, {}, {}
    pen = TTGlyphPen(None)
    glyphs[".notdef"] = pen.glyph()
    # .notdef = caixa
    pen = TTGlyphPen(None)
    pen.moveTo((PX, 0)); pen.lineTo((PX, 7 * PX)); pen.lineTo((5 * PX, 7 * PX)); pen.lineTo((5 * PX, 0)); pen.closePath()
    pen.moveTo((2 * PX, PX)); pen.lineTo((4 * PX, PX)); pen.lineTo((4 * PX, 6 * PX)); pen.lineTo((2 * PX, 6 * PX)); pen.closePath()
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (6 * PX, PX)
    order = [".notdef"]
    for ch in chars:
        pts, w = glyph_pixels(ch)
        name = "uni%04X" % ord(ch)
        pen = TTGlyphPen(None)
        for y in sorted({p[1] for p in pts}):
            xs = sorted(x for x, yy in pts if yy == y)
            runs, s = [], xs[0]
            for a, b in zip(xs, xs[1:] + [None]):
                if b is None or b != a + 1:
                    runs.append((s, a))
                    if b is not None:
                        s = b
            ytop = (base_row - y) * PX
            ybot = ytop - PX
            for (x0, x1) in runs:
                l, r = x0 * PX, (x1 + 1) * PX
                # sentido horário (TrueType)
                pen.moveTo((l, ybot)); pen.lineTo((l, ytop)); pen.lineTo((r, ytop)); pen.lineTo((r, ybot)); pen.closePath()
        glyphs[name] = pen.glyph()
        adv = (w + 1) * PX if ch != " " else 3 * PX
        metrics[name] = (adv, 0)
        cmap[ord(ch)] = name
        order.append(name)
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=asc_rows * PX, descent=-2 * PX)
    fb.setupNameTable({"familyName": "UltimaSementePixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=asc_rows * PX, sTypoDescender=-2 * PX, usWinAscent=asc_rows * PX, usWinDescent=2 * PX,
                sxHeight=5 * PX, sCapHeight=7 * PX)
    fb.setupPost()
    path = os.path.join(OUT, "pixel.ttf")
    os.makedirs(OUT, exist_ok=True)
    fb.save(path)
    return path


if __name__ == "__main__":
    print(build())
